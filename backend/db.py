"""SQLite access for the Campus Customs catalogue, inventory, and users.

See output/harness.md for the schema and the product contract built here.
"""
from __future__ import annotations

import json
import os
import sqlite3
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DATA_DIR = ROOT / "data"
DB_PATH = Path(os.getenv("DB_PATH") or DATA_DIR / "campus_customs.db")
PRODUCTS_DIR = DATA_DIR / "products"
CUTOUT_DIR = DATA_DIR / "products_cutout"  # generated by scripts/make_cutouts.py (P9)
DEFAULT_IMAGE_BG = "#ffffff"

SIZE_ORDER = ["XS", "S", "M", "L", "XL", "XXL"]

# Order matters: "short-sleeve crew-neck t-shirt" must hit T-Shirts before Crewnecks.
CATEGORY_RULES: list[tuple[tuple[str, ...], str]] = [
    (("hood",), "Hoodies"),
    (("quarter-zip",), "Quarter-Zips"),
    (("t-shirt",), "T-Shirts"),
    (("crew", "mockneck"), "Crewnecks"),
    (("long-sleeve",), "Long Sleeve"),
    (("jacket",), "Jackets & Fleece"),
]
CATEGORIES = [name for _, name in CATEGORY_RULES]


_cutouts: tuple[float, dict] = (0.0, {})


def cutout_manifest() -> dict:
    """{product_id: {"bg": "#hex", ...}}; reloaded when the file changes, {} if absent."""
    global _cutouts
    path = CUTOUT_DIR / "manifest.json"
    try:
        mtime = path.stat().st_mtime
    except FileNotFoundError:
        return {}
    if mtime != _cutouts[0]:
        _cutouts = (mtime, json.loads(path.read_text()))
    return _cutouts[1]


def connect() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def categorize(garment_type: str) -> str:
    g = garment_type.lower()
    for keywords, name in CATEGORY_RULES:
        if any(k in g for k in keywords):
            return name
    return "Other"


STUB_MARKER = "filename-based stub"


def display_description(row: sqlite3.Row) -> str:
    """3 catalogue rows have placeholder descriptions (harness.md quirk #2); show a neutral one."""
    if STUB_MARKER in row["description"]:
        return f"{row['name']}, a {row['garment_type']} from our Yale collection."
    return row["description"]


def build_product(row: sqlite3.Row, inventory_rows: list[sqlite3.Row]) -> dict:
    """Single product contract shared by the storefront and (later) the chatbot."""
    inventory = sorted(
        ({"size": r["size"], "quantity": r["quantity"]} for r in inventory_rows),
        key=lambda i: SIZE_ORDER.index(i["size"]) if i["size"] in SIZE_ORDER else 99,
    )
    return {
        "product_id": row["product_id"],
        "name": row["name"],
        "garment_type": row["garment_type"],
        "category": categorize(row["garment_type"]),
        "description": display_description(row),
        "colors": json.loads(row["colors"]),
        "search_tags": json.loads(row["search_tags"]),
        "image_file_path": row["image_file_path"],
        "image_url": f"/media/{row['image_file_path']}",
        # Background-removed cutout + contrasting backdrop (dark merch on white, light on charcoal).
        **_display_image(row["product_id"], row["image_file_path"]),
        "price": row["price"],
        "inventory": inventory,
        "total_stock": sum(i["quantity"] for i in inventory),
    }


def _display_image(product_id: str, image_file_path: str) -> dict:
    info = cutout_manifest().get(product_id)
    if info and (CUTOUT_DIR / f"{product_id}.webp").exists():
        return {"display_image_url": f"/media/products_cutout/{product_id}.webp", "image_bg": info["bg"]}
    return {"display_image_url": f"/media/{image_file_path}", "image_bg": DEFAULT_IMAGE_BG}


def _inventory_by_product(conn: sqlite3.Connection) -> dict[str, list[sqlite3.Row]]:
    grouped: dict[str, list[sqlite3.Row]] = {}
    for r in conn.execute("SELECT product_id, size, quantity FROM inventory"):
        grouped.setdefault(r["product_id"], []).append(r)
    return grouped


def list_products() -> list[dict]:
    with connect() as conn:
        inv = _inventory_by_product(conn)
        rows = conn.execute("SELECT * FROM catalogue ORDER BY name").fetchall()
        return [build_product(r, inv.get(r["product_id"], [])) for r in rows]


def get_product(product_id: str) -> dict | None:
    with connect() as conn:
        row = conn.execute(
            "SELECT * FROM catalogue WHERE product_id = ?", (product_id,)
        ).fetchone()
        if row is None:
            return None
        inv = conn.execute(
            "SELECT size, quantity FROM inventory WHERE product_id = ?", (product_id,)
        ).fetchall()
        return build_product(row, inv)


def search_text(product: dict) -> str:
    return " ".join(
        [
            product["name"],
            product["garment_type"],
            product["description"],
            " ".join(product["colors"]),
            " ".join(product["search_tags"]),
        ]
    ).lower()
